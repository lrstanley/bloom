// Command gen writes nodes.gen.go in package bloom: the builder methods the
// node types share, such as ID and On, for each type listed in builders.go,
// and nodeMeta, which reads the meta of any of them. A method promoted from
// the meta a node embeds would return the meta rather than the node, and
// would be promoted again to a component that embeds a node, so each type
// has its own. Run it with go generate, from package bloom.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log/slog"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"
)

// output is the file written in package bloom.
const output = "nodes.gen.go"

// node is an exported node type.
type node struct {
	Type string // the type's name
	Noun string // what the documentation calls it
}

// builder is a builder method that node types share.
type builder struct {
	Name    string            // the method's name
	Params  string            // its type parameters and parameters; none when empty
	Body    string            // the statements that change n, the node's copy
	Imports []string          // the packages its parameters and body use
	Doc     string            // its documentation, as a template given the node
	Docs    map[string]string // documentation for the types named, in place of Doc
	Only    []string          // the types that have it; all when empty
	Except  []string          // the types that do not have it
}

// has reports whether type t has the builder.
func (b *builder) has(t string) bool {
	if len(b.Only) > 0 && !slices.Contains(b.Only, t) {
		return false
	}
	return !slices.Contains(b.Except, t)
}

func main() {
	dir := flag.String("dir", ".", "the directory of package bloom")
	flag.Parse()

	src, err := generate(*dir)
	if err == nil {
		err = os.WriteFile(filepath.Join(*dir, output), src, 0o644) //nolint:gosec // source files.
	}
	if err != nil {
		slog.Error("generating builders", "error", err) //nolint:sloglint // a command's own logger.
		os.Exit(1)
	}
}

// file is the template of the file written, given the node types, the
// methods, the imports they use, and the aliases of those imports.
var file = template.Must(template.New(output).Funcs(template.FuncMap{"comment": comment}).Parse(`// Copyright (c) Liam Stanley <liam@liam.sh>. All rights reserved. Use of
// this source code is governed by the MIT license that can be found in
// the LICENSE file.

// Code generated by internal/gen from internal/gen/builders.go. DO NOT EDIT.

package bloom

import (
{{- range .Imports}}
	{{index $.Aliases .}} "{{.}}"
{{- end}}
)

// nodeMeta sets to to the meta of c, and reports true, when c is one of
// the node types.
func nodeMeta(c Child, to *meta) bool {
	switch n := c.(type) {
{{- range .Nodes}}
	case {{.Type}}:
		*to = n.meta
{{- end}}
	default:
		return false
	}
	return true
}
{{range .Methods}}
{{comment .Doc}}func (n {{.Type}}) {{.Name}}{{or .Params "()"}} {{.Type}} {
	{{.Body}}
	return n
}
{{end}}`))

// method is a builder method written for a node type.
type method struct {
	Type   string // the node type it is written for
	Name   string // the builder's name
	Params string // the builder's parameters
	Body   string // the builder's body
	Doc    string // its documentation for the type
}

// generate returns the source of the builders for package bloom in dir,
// after checking that the node types listed are the ones that embed meta.
func generate(dir string) ([]byte, error) {
	if err := check(dir); err != nil {
		return nil, err
	}

	var methods []method
	imports := map[string]bool{}
	for _, n := range nodes {
		for _, b := range builders {
			if !b.has(n.Type) {
				continue
			}
			doc, err := b.doc(n)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", n.Type, b.Name, err)
			}
			methods = append(methods, method{Type: n.Type, Name: b.Name, Params: b.Params, Body: b.Body, Doc: doc})
			for _, imp := range b.Imports {
				imports[imp] = true
			}
		}
	}

	var buf bytes.Buffer
	err := file.Execute(&buf, map[string]any{
		"Imports": slices.Sorted(maps.Keys(imports)),
		"Nodes":   nodes,
		"Aliases": aliases,
		"Methods": methods,
	})
	if err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting: %w", err)
	}
	return src, nil
}

// aliases are the names imports are given where the package's name is not
// the last element of its path.
var aliases = map[string]string{
	"charm.land/bubbletea/v2": "tea",
}

// doc returns the builder's documentation for node n.
func (b *builder) doc(n node) (string, error) {
	text, ok := b.Docs[n.Type]
	if !ok {
		text = b.Doc
	}
	if text == "" {
		return "", errors.New("no documentation")
	}
	tmpl, err := template.New("").Option("missingkey=error").Parse(text)
	if err != nil {
		return "", err
	}
	var out strings.Builder
	err = tmpl.Execute(&out, n)
	return out.String(), err
}

// width is the widest a line of documentation gets, its "// " included.
const width = 78

// comment returns text as a doc comment, its paragraphs wrapped.
func comment(text string) string {
	var sb strings.Builder
	for i, para := range strings.Split(text, "\n\n") {
		if i > 0 {
			sb.WriteString("//\n")
		}
		line := "//"
		for word := range strings.FieldsSeq(para) {
			if len(line) > len("//") && len(line)+1+len(word) > width {
				sb.WriteString(line + "\n")
				line = "//"
			}
			line += " " + word
		}
		sb.WriteString(line + "\n")
	}
	return sb.String()
}

// check returns an error unless the node types listed are exactly the
// exported types of package bloom in dir that embed meta, and every type a
// builder names is listed.
func check(dir string) error {
	fset := token.NewFileSet()
	embed := map[string]bool{}
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || filepath.Base(path) == output {
			continue
		}
		f, perr := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if perr != nil {
			return perr
		}
		for _, decl := range f.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, _ := spec.(*ast.TypeSpec)
				if st, isStruct := ts.Type.(*ast.StructType); isStruct && ts.Name.IsExported() && embedsMeta(st) {
					embed[ts.Name.Name] = true
				}
			}
		}
	}

	var errs []error
	listed := map[string]bool{}
	for _, n := range nodes {
		listed[n.Type] = true
		if !embed[n.Type] {
			errs = append(errs, fmt.Errorf("%s is listed but is not an exported type that embeds meta", n.Type))
		}
	}
	for _, t := range slices.Sorted(maps.Keys(embed)) {
		if !listed[t] {
			errs = append(errs, fmt.Errorf("%s embeds meta but is not listed in nodes", t))
		}
	}
	for _, b := range builders {
		named := slices.Concat(b.Only, b.Except, slices.Collect(maps.Keys(b.Docs)))
		for _, t := range named {
			if !listed[t] {
				errs = append(errs, fmt.Errorf("builder %s names %s, which is not listed in nodes", b.Name, t))
			}
		}
	}
	return errors.Join(errs...)
}

// embedsMeta reports whether st embeds meta.
func embedsMeta(st *ast.StructType) bool {
	for _, f := range st.Fields.List {
		if id, ok := f.Type.(*ast.Ident); ok && len(f.Names) == 0 && id.Name == "meta" {
			return true
		}
	}
	return false
}
